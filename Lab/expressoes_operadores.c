#include <stdio.h>

int main() {
    int a = 15, b = 4;

    printf("Soma: %d + %d = %d\n", a, b, a + b);
    printf("Subtracao: %d - %d = %d\n", a, b, a - b);
    printf("Multiplicacao: %d * %d = %d\n", a, b, a * b);
    printf("Divisao Inteira: %d / %d = %d\n", a, b, a / b);
    printf("Resto da Divisao: %d %% %d = %d\n", a, b, a % b);

    return 0;
}
